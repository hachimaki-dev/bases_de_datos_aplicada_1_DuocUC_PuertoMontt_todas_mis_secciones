DROP TABLE facturas CASCADE CONSTRAINTS;
DROP TABLE vendedores CASCADE CONSTRAINTS;
DROP TABLE articulos CASCADE CONSTRAINTS;
DROP TABLE clientes CASCADE CONSTRAINTS;
DROP TABLE zonas CASCADE CONSTRAINTS;
DROP TABLE categorias CASCADE CONSTRAINTS;
DROP TABLE marcas CASCADE CONSTRAINTS;
DROP TABLE comunas CASCADE CONSTRAINTS;



CREATE TABLE comunas (
    id          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nom_comuna  VARCHAR2(40) NOT NULL UNIQUE
);

CREATE TABLE marcas (
    id          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nom_marca   VARCHAR2(40) NOT NULL UNIQUE
);

CREATE TABLE categorias (
    id             NUMBER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nom_categoria  VARCHAR2(30) NOT NULL,
    porcentaje     NUMBER(4, 1)    NOT NULL CHECK (porcentaje > 0) 
);

CREATE TABLE zonas (
    id        NUMBER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nom_zona  VARCHAR2(40)  NOT NULL UNIQUE,
    porc      NUMBER(5, 2) NOT NULL
);

CREATE TABLE clientes (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, nombre_cliente VARCHAR2(60), direccion VARCHAR2(60) NOT NULL, telefono VARCHAR2(15) NOT NULL, comunaId REFERENCES comunas(id) NOT NULL);

CREATE TABLE articulos (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, nombre_articulo VARCHAR2(50) NOT NULL, precio NUMBER(8) NOT NULL ,stock_actual NUMBER(5) NOT NULL, stock_minimo NUMBER(5) NOT NULL, marca_id  NUMBER REFERENCES marcas(id));

CREATE TABLE vendedores (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, rut_vendedor VARCHAR2(12), nombre1 VARCHAR2(30) NOT NULL, apellido_paterno VARCHAR2(30) NOT NULL, apellido_maternal VARCHAR2(30), 
fecha_nacimiento DATE, fecha_contato DATE NOT NULL, sueldo NUMBER(8) NOT NULL,
comision NUMBER(4) NOT NULL, zonaid NUMBER REFERENCES zonas(id), categoria_id NUMBER REFERENCES categorias(id) NOT NULL);

CREATE TABLE facturas (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, cliente_id NUMBER REFERENCES clientes(id), vendedorid NUMBER REFERENCES vendedores(id), fecha_factura DATE NOT NULL);


CREATE TABLE DETALLE_FACTURA (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, factura_id NUMBER REFERENCES FACTURAS(id) NOT NULL, articulo_id REFERENCES ARTICULOS(id) NOT NULL, cantidad NUMBER NOT NULL)




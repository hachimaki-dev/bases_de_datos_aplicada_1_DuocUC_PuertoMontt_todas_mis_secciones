


SELECT NOM_COMUNA,  SUM(df.cantidad) AS TOTAL_VENTAS FROM comunas c INNER JOIN CLIENTES cl ON cl.ID = cl.COMUNAID INNER JOIN FACTURAS f ON cl.ID = f.CLIENTE_ID
INNER JOIN DETALLE_FACTURA df ON f.ID = df.FACTURA_ID GROUP BY c.NOM_COMUNA ORDER BY TOTAL_VENTAS DESC;

SELECT v.NOMBRE1,  SUM(df.cantidad * a.precio) AS TOTAL_VENTAS FROM VENDEDORES v INNER JOIN FACTURAS f ON v.ID = f.VENDEDORID INNER JOIN DETALLE_FACTURA df ON f.ID = df.FACTURA_ID
INNER JOIN ARTICULOS a ON df.ARTICULO_ID = a.ID GROUP BY v.NOMBRE1 ORDER BY TOTAL_VENTAS DESC;
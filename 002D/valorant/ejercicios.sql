--#25 En patrocinios, mostrar por cada tipo_contrato la cantidad de contratos y la suma de monto_anual, ordenado de mayor a menor monto total.

SELECT * FROM PATROCINIOS;
SELECT tipo_contrato, COUNT(id) AS CANTIDAD_CONTRATOS, SUM(monto_anual) AS MONTO_TOTAL  FROM PATROCINIOS GROUP BY TIPO_CONTRATO ORDER BY MONTO_TOTAL DESC;

--#26 En participaciones, agrupar por gano (S o N) y mostrar la cantidad de registros, el promedio de kills y el promedio de puntaje_combate.

SELECT * FROM PARTICIPACIONES;
SELECT GANO, COUNT(ID) AS CANTIDAD_REGISTROS, ROUND(AVG(KILLS),1) AS PROMEDIO_KILLS, ROUND(AVG(PUNTAJE_COMBATE),1) AS PROMEDIO_PUNTAJE_COMBATE FROM PARTICIPACIONES GROUP BY GANO;

--#27 En jugadores, mostrar por cada equipo_id la cantidad de jugadores, el sueldo mínimo, el sueldo máximo y la suma de sueldos.

SELECT * FROM JUGADORES;
SELECT EQUIPO_ID, COUNT(ID) AS CANTIDAD_JUGADORES, MIN(SUELDO_MENSUAL) AS SUELDO_MAS_BAJO, MAX(SUELDO_MENSUAL) AS SUELDO_MAS_ALTO, SUM(SUELDO_MENSUAL) AS TOTAL_SUELDOS FROM JUGADORES GROUP BY EQUIPO_ID;


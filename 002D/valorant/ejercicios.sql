-- #23 Por cada fase en la tabla partidas, mostrar cuántas partidas se jugaron, la duración promedio y el total de público acumulado.

SELECT * FROM PARTIDAS;
SELECT  FASE,COUNT(ID) AS PARTIDAS_JUGADAS, ROUND(AVG(duracion_min),1) AS DURACION_PROMEDIO, SUM(asistencia_publico) AS PUBLICO_TOTAL FROM PARTIDAS GROUP BY FASE;


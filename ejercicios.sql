// Me trae todas las columas de jugadores
SELECT * FROM JUGADORES;

SELECT AVG(EDAD) as edad_promedio FROM JUGADORES;
// que pasa si ademas me quiero traer el nombre de los jugadores
SELECT AVG(EDAD) AS EDAD_PROMEDIO FROM JUGADORES GROUP BY NOMBRE_REAL;

SELECT AVG(EDAD), PAIS_NATAL FROM JUGADORES GROUP BY PAIS_NATAL;

SELECT COUNT(ID) AS TOTAL_JUGADORES , AVG(SUELDO_MENSUAL) AS SUELDO_PROMEDIO , MIN(SUELDO_MENSUAL)  AS SUELDO_MAS_BAJO, MAX(SUELDO_MENSUAL) AS SUELDO_MAS_ALTO FROM JUGADORES GROUP BY PAIS_NATAL;

SELECT COUNT(ID) , ROL FROM AGENTES GROUP BY ROL;

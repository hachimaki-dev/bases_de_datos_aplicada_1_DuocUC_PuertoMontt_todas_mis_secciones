SELECT * FROM COMUNAS;
SELECT * FROM ARTICULOS;
SELECT * FROM DETALLE_FACTURA;
SELECT * FROM FACTURAS;
SELECT * FROM CLIENTES;

---------------------------------------------------------------------------------------------

SELECT co.NOM_COMUNA, SUM(df.CANTIDAD) AS CANTIDAD_VENTAS FROM COMUNAS co
JOIN CLIENTES cl ON co.ID_COMUNAS = cl.ID_COMUNAS
JOIN FACTURAS fa ON cl.ID_CLIENTES = fa.ID_CLIENTES
JOIN DETALLE_FACTURA df ON fa.ID_FACTURAS = df.ID_FACTURAS
JOIN ARTICULOS a ON a.ID_ARTICULOS = df.ID_ARTICULOS
GROUP BY co.NOM_COMUNA
ORDER BY CANTIDAD_VENTAS DESC;
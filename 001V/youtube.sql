DROP TABLE USUARIO;
DROP TABLE CANAL;
DROP TABLE CATEGORIA;
DROP TABLE VIDEO;
DROP TABLE COMENTARIO;
DROP TABLE SUSCRIPCION;

CREATE TABLE USUARIO(
    id_usuario NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) UNIQUE NOT NULL,
    fecha_registro DATE
);

CREATE TABLE CANAL(
    id_canal NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(500) NOT NULL,
    id_usuario REFERENCES USUARIO(id_usuario)
);

CREATE TABLE CATEGORIA(
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(100) NOT NULL

);

CREATE TABLE VIDEO(
    id_video NUMBER GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR2(200) NOT NULL,
    descripcion VARCHAR2(500) NOT NULL,
    fecha_publicacion DATE,
    duracion NUMBER NOT NULL

);

CREATE TABLE COMENTARIO(
    id_comentario NUMBER GENERATED BY DEFAULT AS IDENTITY,
    texto VARCHAR2(1000) NOT NULL,
    fecha_comentario DATE
);

CREATE TABLE SUSCRIPCION(
    id_suscripcion NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha_suscripcion DATE
);

 



SELECT j.NICKNAME, p.KILLS, p.DEATHS, p.ASSISTS, p.PUNTAJE_COMBATE, p.GANO FROM PARTICIPACIONES p
JOIN JUGADORES j  ON p.JUGADOR_ID = j.ID ;

--Puedo entonces colocar el nombre del personaje con el que se jugo la partida????
SELECT j.NICKNAME, a.NOMBRE, p.KILLS, p.DEATHS, p.ASSISTS, p.PUNTAJE_COMBATE, p.GANO FROM PARTICIPACIONES p
JOIN JUGADORES j  ON p.JUGADOR_ID = j.ID
JOIN AGENTES a ON p.AGENTE_ID = a.ID ;

--Puedo ordenar por algun criterio?
SELECT j.NICKNAME, a.NOMBRE, p.KILLS, p.DEATHS, p.ASSISTS, p.PUNTAJE_COMBATE, p.GANO FROM PARTICIPACIONES p
JOIN JUGADORES j  ON p.JUGADOR_ID = j.ID
JOIN AGENTES a ON p.AGENTE_ID = a.ID ORDER BY p.PUNTAJE_COMBATE DESC;


--Ordenar por partidas ganadas primero
SELECT j.NICKNAME, a.NOMBRE, p.KILLS, p.DEATHS, p.ASSISTS, p.PUNTAJE_COMBATE, p.GANO FROM PARTICIPACIONES p
JOIN JUGADORES j  ON p.JUGADOR_ID = j.ID
JOIN AGENTES a ON p.AGENTE_ID = a.ID ORDER BY p.GANO DESC, p.PUNTAJE_COMBATE;


SELECT * FROM COMUNAS;
SELECT * FROM ARTICULOS;
SELECT * FROM DETALLE_FACTURA;
SELECT * FROM FACTURAS;

SELECT co.NOM_COMUNA, SUM(df.CANTIDAD) AS CANTIDAD_VENTAS FROM COMUNAS co
JOIN CLIENTES ON co.ID = CLIENTES.COMUNA_ID
JOIN FACTURAS fa ON CLIENTES.ID = fa.CLIENTE_ID
JOIN DETALLE_FACTURA df ON fa.ID = df.FACTURAS_ID
JOIN ARTICULOS ar ON ar.ID = df.ARTICULO_ID
GROUP BY co.NOM_COMUNA
ORDER BY CANTIDAD_VENTAS DESC;
--V1
SELECT * FROM JUGADORES;
SELECT EQUIPO_ID,  COUNT(NICKNAME), MIN(SUELDO_MENSUAL), MAX(SUELDO_MENSUAL), SUM(SUELDO_MENSUAL) FROM JUGADORES GROUP BY EQUIPO_ID;
--V2
SELECT EQUIPO_ID,  COUNT(NICKNAME) AS CANTIDAD_JUGADORES , MIN(SUELDO_MENSUAL) AS SUELDO_MINIMO, MAX(SUELDO_MENSUAL) AS SUELDO_MAXIMO, SUM(SUELDO_MENSUAL) AS SALARIO_TOTAL_DEL_EQUIPO FROM JUGADORES GROUP BY EQUIPO_ID;

--V3
SELECT EQUIPO_ID,  COUNT(NICKNAME) AS CANTIDAD_JUGADORES , MIN(SUELDO_MENSUAL) AS SUELDO_MINIMO, MAX(SUELDO_MENSUAL) AS SUELDO_MAXIMO, SUM(SUELDO_MENSUAL) AS SALARIO_TOTAL_DEL_EQUIPO FROM JUGADORES GROUP BY EQUIPO_ID ORDER BY SUELDO_MINIMO, EQUIPO_ID DESC ;


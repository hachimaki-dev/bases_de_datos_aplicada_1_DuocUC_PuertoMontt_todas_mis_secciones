--Que tablas estan involucradas??? 
--JUGADORES - PARTIDAS - MAPAS - PARTICIPACIONES
SELECT * FROM JUGADORES;
SELECT * FROM PARTIDAS;
SELECT * FROM MAPAS;
SELECT * FROM PARTICIPACIONES;

SELECT j.NICKNAME AS JUGADOR, pa.FASE, ma.NOMBRE AS NOMBRE_DEL_MAPA, p.KILLS FROM JUGADORES j
JOIN PARTICIPACIONES p ON p.JUGADOR_ID = j.ID 
JOIN PARTIDAS pa ON p.PARTIDA_ID = pa.ID 
JOIN MAPAS ma ON pa.MAPA_ID = ma.ID
WHERE pa.FASE = 'Gran Final'  ORDER BY KILLS DESC;